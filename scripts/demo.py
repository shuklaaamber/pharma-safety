"""Generate docs/demo-walkthrough.md from a real run against a THROWAWAY database.

Usage: python scripts/demo.py [output_path]
Synthetic data only. The external LLM is never called (extractive answers), and the
real data/ database is never touched.
"""
from __future__ import annotations

import sys
import tempfile
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from pharma_intake import workflow  # noqa: E402
from pharma_intake.agent.orchestrator import AgentOrchestrator  # noqa: E402
from pharma_intake.db import Database  # noqa: E402
from pharma_intake.rag.pipeline import (  # noqa: E402
    HybridRetriever, load_report_documents, load_sop_documents,
)
from pharma_intake.validation import validate_intake  # noqa: E402

OUT_DEFAULT = ROOT / "docs" / "demo-walkthrough.md"


def _fence(text: str) -> str:
    return f"```text\n{text.rstrip()}\n```\n"


def main(out_path: Path) -> None:
    md: list[str] = [
        "# Demo Walkthrough\n",
        "> Generated by `scripts/demo.py` against a temporary database. **Synthetic data only.** "
        "No external LLM call is made (extractive mode). This tool never assesses causality, "
        "recommends treatment or determines reportability.\n",
    ]
    today = date.today()
    received = today - timedelta(days=2)
    onset = today - timedelta(days=4)

    with tempfile.TemporaryDirectory() as tmp:
        db = Database(Path(tmp) / "demo.db")

        # 1. Validation errors (nothing is saved)
        md.append("## 1. Validation rejects an incomplete report\n")
        bad = validate_intake(
            report_type="Suspected Adverse Event", product_name="Examplomab", batch_lot="LOT-12",
            date_received=received, reporter_type="Consumer", description="Rash reported",
            event_description="", onset_date=None,
        )
        md.append(_fence("\n".join(f"- {e}" for e in bad.errors)))

        # 2. Two fictional reports
        md.append("## 2. Two fictional reports are saved\n")
        ae = validate_intake(
            report_type="Suspected Adverse Event", product_name="Examplomab", batch_lot="LOT-88392",
            date_received=received, reporter_type="Healthcare Professional",
            description="Reporter described a skin reaction after a dose.",
            event_description="Hives and difficulty breathing", onset_date=onset,
        )
        pqc = validate_intake(
            report_type="Product Quality Complaint", product_name="Examplomab",
            batch_lot="LOT-12345", date_received=received, reporter_type="Consumer",
            description="Blister packaging was torn and the label was smudged.",
        )
        assert ae.ok and pqc.ok, (ae.errors, pqc.errors)
        ref_ae, ref_pqc = db.create_report(ae.report), db.create_report(pqc.report)
        rows = [f"{ref_ae}  Suspected Adverse Event      LOT-88392  status={db.get_report(ref_ae)['status']}",
                f"{ref_pqc}  Product Quality Complaint    LOT-12345  status={db.get_report(ref_pqc)['status']}"]
        md.append(_fence("\n".join(rows)))

        # 3. Lifecycle with HITL
        md.append("## 3. Status lifecycle with human-in-the-loop closure\n")
        steps: list[str] = []
        r = workflow.request_status_change(db, ref_ae, "In Review")
        steps.append(f"New -> In Review: {r.message}")
        r = workflow.request_status_change(db, ref_ae, "Closed")
        steps.append(f"Request Closed: {r.message} (pending_approval={r.pending_approval})")
        steps.append(f"Status while frozen: {db.get_report(ref_ae)['status']}")
        r = workflow.decide_closure(db, ref_ae, "Approved", "REV-001", "QA Lead",
                                    "Documentation complete; closure approved.")
        steps.append(f"Reviewer REV-001 decision: {r.message}")
        steps.append(f"Final status: {db.get_report(ref_ae)['status']}")
        r = workflow.request_status_change(db, ref_pqc, "Closed")
        steps.append(f"Illegal skip New -> Closed on {ref_pqc}: {r.message}")
        md.append(_fence("\n".join(steps)))

        # 4. Agent: RAG, scope refusal, chat HITL
        md.append("## 4. Ask tab (agent control plane)\n")
        orch = AgentOrchestrator(
            db, lambda: HybridRetriever(load_sop_documents() + load_report_documents(db)))
        for q in ("LOT-88392 hives", "difficulty breathing",
                  "Did Examplomab cause the reaction?", f"move {ref_pqc} to in review",
                  f"close {ref_pqc}"):
            resp = orch.handle(q)
            md.append(f"**Q:** `{q}`  \n**Route:** {resp.route.value}\n")
            md.append(_fence(resp.text))
        md.append("**ReAct trace (short-term memory)**\n")
        md.append(_fence("\n".join(
            f"{i}. thought: {t.thought} | action: {t.action} | observation: "
            f"{t.observation.splitlines()[0]}" for i, t in enumerate(orch.short_term.steps, 1))))

        # 5. Circuit breaker
        md.append("## 5. Circuit breaker\n")
        outs = []
        for i in range(1, 5):
            res = orch.call_tool("update_status", {"ref": "BAD", "target_status": "Nope"})
            outs.append(f"call {i}: {res.code or 'ok'}")
        md.append(_fence("\n".join(outs)))
        orch.reset_breaker()

        # 6. Audit dump
        md.append("## 6. Audit log (append-only; metadata only, no free text)\n")
        lines = [f"{e['id']:>3}  {e['ts_utc']}  {e['action']:<24} {e['ref'] or '-':<14} "
                 f"{e['detail'] or '-':<18} {e['actor']}" for e in db.audit_events()]
        md.append(_fence("\n".join(lines)))

    out_path.write_text("\n".join(md), encoding="utf-8")
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else OUT_DEFAULT)
